"""Расчёт под FPV: центровка с камерами, управление креном, дальность видео.

    python sim/fpv.py

Три вопроса, от которых зависит конструкция:

1. Где окажется центр масс, если 800 г камер и передатчика поставить в нос.
   Это лечит заднюю центровку от двигателя 800 г.
2. Сколько нужна площадь элеронов, чтобы стабилизировать крен. Без этого
   картинка с камеры будет вращаться, и FPV не работает.
3. Хватит ли мощности передатчика, чтобы видеть полёт на дистанции полёта.
"""

from __future__ import annotations

import math
import sys

RHO = 1.2
G = 9.81
C_LIGHT = 299_792_458.0

# Компоненты: масса (кг), положение центра от носа (м).
# FPV-оборудование ставится в нос — это и есть главный рычаг центровки.
COMPONENTS_FPV = (
    ("камера и передатчик 800 г", 0.80, 0.12),
    ("двигатель с топливом", 0.80, 0.95),
    ("корпус, хвост, оперение", 0.35, 0.55),
    ("машинки и тяги", 0.12, 0.50),
    ("питание и электроника", 0.10, 0.30),
)

FUSELAGE_LENGTH = 1.10
CL_MAX = 1.1
AR = 6.0
WING_MASS_PER_M2 = 1.2


def main() -> int:
    fixed = sum(m for _n, m, _x in COMPONENTS_FPV)
    moment = sum(m * x for _n, m, x in COMPONENTS_FPV)

    print("Центровка с камерами в носу")
    print(f"  {'компонент':<28}{'масса':>9}{'положение':>12}")
    for name, mass, position in COMPONENTS_FPV:
        print(f"  {name:<28}{mass * 1000:>7.0f} г{position * 100:>10.0f} см")
    cg_no_wing = moment / fixed
    print(f"  {'итого без крыла':<28}{fixed * 1000:>7.0f} г{cg_no_wing * 100:>10.0f} см")
    print()

    # Крыло подбираем вместе с его массой
    area = 0.20
    for _ in range(8):
        wing_mass = area * WING_MASS_PER_M2
        total = fixed + wing_mass
        area = 2.0 * total * G / (RHO * 22.0 ** 2 * 0.5)
    wing_mass = area * WING_MASS_PER_M2
    total = fixed + wing_mass
    span = math.sqrt(area * AR)
    chord = area / span
    stall = math.sqrt(2.0 * total * G / (RHO * area * CL_MAX))

    # Крыло ставим так, чтобы центр масс лёг на четверть хорды
    def cg_for(leading_edge: float) -> float:
        wing_position = leading_edge + chord * 0.5
        return (moment + wing_mass * wing_position) / total

    leading_edge = cg_no_wing - chord * 0.25
    for _ in range(10):
        cg = cg_for(leading_edge)
        leading_edge = cg - chord * 0.25
    cg = cg_for(leading_edge)

    print("Что изменилось")
    print(f"  полная масса:               {total:.2f} кг")
    print(f"  крыло:                      {area * 1e4:.0f} см², размах "
          f"{span * 100:.0f} см, хорда {chord * 100:.0f} см")
    print(f"  скорость срыва:             {stall:.1f} м/с")
    print(f"  центр масс:                 {cg * 100:.0f} см от носа "
          f"(было 58 см при оборудовании в середине)")
    print(f"  передняя кромка крыла:      {leading_edge * 100:.0f} см от носа")
    print(f"  за крылом на хвост:         "
          f"{(FUSELAGE_LENGTH - leading_edge - chord) * 100:.0f} см")
    print("  Камеры в носу сдвинули центр масс вперёд примерно на 6 см —")
    print("  это ровно то, чего не хватало из-за тяжёлого двигателя.")
    print()

    # --- управление креном ---
    print("Управление креном: без него FPV не работает")
    speed = 25.0
    q = 0.5 * RHO * speed * speed
    # Демпфирование крена крылом: момент на радиан в секунду
    damping = q * area * span * span / (2.0 * speed) * 0.4
    # Эффективность элерона: местный прирост коэффициента подъёмной силы
    # берётся как Cl_alpha * tau, где tau — доля эффективности закрылка
    cl_alpha_2d = 4.5
    tau = 0.5
    deflection = math.radians(20.0)
    arm = 0.4 * (span / 2.0)
    per_area = 2.0 * q * cl_alpha_2d * tau * deflection * arm
    print(f"  скоростной напор при 25 м/с:{q:.0f} Па")
    print(f"  демпфирование крена:        {damping:.2f} Н·м на радиан/с")
    print(f"  {'желаемый крен':>16}{'нужен момент':>15}{'элероны':>12}{'доля крыла':>13}")
    for rate_deg in (60.0, 90.0, 120.0):
        rate = math.radians(rate_deg)
        need = damping * rate
        aileron = need / per_area
        print(f"  {rate_deg:>14.0f}°/с{need:>13.2f} Н·м{aileron * 1e4:>10.0f} см²"
              f"{aileron / area * 100:>12.1f} %")
    print("  Для крена 90°/с хватает элеронов на 4-6% площади крыла —")
    print("  это обычный размер. Меньше 3% будет вяло, больше 10% начнёт")
    print("  раскачивать аппарат: элероны работают и против собственного")
    print("  демпфирования крыла.")
    print()

    # --- дальность видео ---
    print("Дальность видеопередачи")
    print("  Свободное затухание: FSPL = 20*log10(4*pi*R/lambda)")
    print("  Запас на замирания 20 дБ: без него расчёт даёт вдесятеро больше,")
    print("  чем получается на практике")
    sensitivity = -90.0  # дБм, типичный приёмник FPV
    antenna_gain = 12.0  # дБ, передающая плюс приёмная
    fade_margin = 20.0
    print(f"  {'частота':>10}{'мощность':>11}{'дальность':>12}{'впритык':>10}")
    for frequency_ghz, power_dbm, label in ((5.8, 25.0, "0,3 Вт"), (5.8, 30.0, "1 Вт"),
                                            (1.2, 25.0, "0,3 Вт"), (1.2, 30.0, "1 Вт")):
        lam = C_LIGHT / (frequency_ghz * 1e9)

        def reach(margin: float) -> float:
            budget = power_dbm + antenna_gain - sensitivity - margin
            return lam * 10 ** (budget / 20.0) / (4.0 * math.pi)

        print(f"  {frequency_ghz:>8.1f} ГГц{label:>11}{reach(fade_margin) / 1000:>10.1f} км"
              f"{reach(0.0) / 1000:>8.1f} км")
    print("  Первый столбец — с запасом на замирания, по нему и надо считать.")
    print("  Полёт уходит на 300-500 м и вверх на 200-300 м: наклонная дальность")
    print("  около 600 м, и запаса хватает даже на 5,8 ГГц с 0,3 Вт.")
    print("  За деревьями и складками рельефа 5,8 ГГц глохнет быстро: если")
    print("  летать низко, лучше 1,2 ГГц.")
    print()

    print("Что из этого следует для управления")
    print("  FPV требует, чтобы картинка не вращалась. Значит нужны три оси:")
    print("    * крен — элероны, иначе изображение крутится;")
    print("    * тангаж — руль высоты, иначе аппарат задерёт нос или впадёт")
    print("      в пикирование;")
    print("    * курс — руль направления, и это то, чем занимается эта программа.")
    print()
    print("  Честный совет по трудозатратам: стабилизация по трём осям —")
    print("  решённая задача, и решать её заново не нужно. Обычный полётный")
    print("  контроллер (30-50 г) делает это лучше и надёжнее, чем всё, что")
    print("  мы напишем сами. Наша новизна — датчик абсолютного курса по свету,")
    print("  и его надо просто подключить к стандартному контроллеру.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
