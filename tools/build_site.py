def build() -> int:
    DOWNLOADS.mkdir(parents=True, exist_ok=True)

    # Отдельные архивы по частям
    total = 0
    for name, (title, files, readme) in PACKS.items():
        target = DOWNLOADS / f"{name}.zip"
        missing = [f for f in files if not f.is_file()]
        if missing:
            print(f"  пропуск {name}: нет файлов {[m.name for m in missing]}")
            continue
        with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
            archive.writestr("README.txt", readme)
            for path in files:
                archive.write(path, path.name)
        size = target.stat().st_size / 1024
        total += size
        print(f"  {target.name:<28} {len(files) + 1:>3} файлов  {size:>7.1f} КБ  ({title})")

    # Общий архив: всё вместе, чтобы можно было скачать одним файлом
    everything = DOWNLOADS / "star-toy-all.zip"
    with zipfile.ZipFile(everything, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, (_title, files, readme) in PACKS.items():
            for path in files:
                archive.write(path, f"{name}/{path.name}")
            archive.writestr(f"{name}/README.txt", readme)
        # Страницы сайта и документация
        for path in sorted(SITE.glob("*.html")) + sorted(SITE.glob("*.css")):
            archive.write(path, f"site/{path.name}")
        for path in sorted((ROOT / "docs").glob("*.md")):
            archive.write(path, f"docs/{path.name}")
        archive.write(ROOT / "README.md", "README.md")
    size = everything.stat().st_size / 1024
    total += size
    print(f"  {everything.name:<28} {'':>3}         {size:>7.1f} КБ  (всё вместе)")

    print(f"\n  всего: {total:.0f} КБ в {len(list(DOWNLOADS.glob('*.zip')))} архивах")
    print(f"  папка: {DOWNLOADS}")
    return 0


if __name__ == "__main__":
    sys.exit(build())
